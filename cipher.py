def to_bin(data): # bytes -> string biner
    return ''.join(f'{b:08b}' for b in data)


def to_bytes(bin_str): # string biner -> bytes
    return bytes(int(bin_str[i:i + 8], 2) for i in range(0, len(bin_str), 8))


def key_bin():
    k = KEY.encode()
    k = (k * 8)[:8]
    return to_bin(k)


def encrypt(plaintext):
    data = plaintext.encode()
    pad = 8 - len(data) % 8
    data += bytes([pad] * pad)
    subkeys = gen_subkeys(key_bin())
    bits = to_bin(data)
    hasil = ''
    for i in range(0, len(bits), 64):
        hasil += des(bits[i:i + 64], subkeys)
    return to_bytes(hasil)


def decrypt(ciphertext):
    subkeys = gen_subkeys(key_bin())[::-1]
    bits = to_bin(ciphertext)
    hasil = ''
    for i in range(0, len(bits), 64):
        hasil += des(bits[i:i + 64], subkeys)
    data = to_bytes(hasil)
    return data[:-data[-1]].decode()